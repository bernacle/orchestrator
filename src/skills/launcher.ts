import { chmodSync, existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve, sep } from "node:path";

/**
 * A stable command for installed skills: `$ORCHESTRATOR_HOME/bin/orchestrator`.
 *
 * Skills must survive deleting a development worktree, moving the checkout, and agent shells
 * whose PATH has another Node first (Codex's login shell resolved `node` to v16). So skills call
 * this shim, never a checkout path or a Node binary directly. The shim:
 *   - knows the package root it was installed from (re-running `skill install` from another
 *     checkout or a global npm/pnpm install repoints it; skills don't change);
 *   - picks a Node >= 22.5 at run time: $ORCHESTRATOR_NODE, the Node that ran the install, nvm
 *     installs, Homebrew, /usr/local, then PATH;
 *   - fails with an actionable message when the package root is gone.
 * It is Orchestrator-owned (a marker line) and never written over a file that isn't.
 */

export const SHIM_MARKER = "# orchestrator-launcher v1 (generated by `orchestrator skill install`; do not edit)";

export function shimPath(home: string): string {
  return join(home, "bin", "orchestrator");
}

function shq(s: string): string {
  return `'${s.replace(/'/g, "'\\''")}'`;
}

export function renderShim(input: { packageRoot: string; node: string }): string {
  return `#!/bin/sh
${SHIM_MARKER}
ORCH_ROOT=${shq(input.packageRoot)}
ORCH_INSTALL_NODE=${shq(input.node)}
ok() { [ -n "$1" ] && [ -x "$1" ] && "$1" -e 'const [a,b]=process.versions.node.split(".").map(Number);process.exit(a>22||(a===22&&b>=5)?0:1)' >/dev/null 2>&1; }
if [ ! -f "$ORCH_ROOT/bin/orchestrator.js" ]; then
  echo "orchestrator: the installation this launcher points at is gone ($ORCH_ROOT)." >&2
  echo "Run \\\`orchestrator skill install --all\\\` from your orchestrator checkout (or a global install) to repoint it." >&2
  exit 127
fi
for n in "$ORCHESTRATOR_NODE" "$ORCH_INSTALL_NODE" "$HOME"/.nvm/versions/node/v*/bin/node /opt/homebrew/bin/node /usr/local/bin/node "$(command -v node 2>/dev/null)"; do
  if ok "$n"; then exec "$n" "$ORCH_ROOT/bin/orchestrator.js" "$@"; fi
done
echo "orchestrator: no Node.js >= 22.5 found (checked ORCHESTRATOR_NODE, $ORCH_INSTALL_NODE, ~/.nvm, Homebrew, /usr/local and PATH). Install Node 24, or set ORCHESTRATOR_NODE." >&2
exit 127
`;
}

export function readShimTarget(file: string): { packageRoot: string; node: string } | null {
  if (!existsSync(file)) return null;
  const text = readFileSync(file, "utf8");
  if (!text.includes(SHIM_MARKER)) return null;
  const get = (k: string) => text.match(new RegExp(`^${k}='((?:[^']|'\\\\'')*)'$`, "m"))?.[1]?.replace(/'\\\\''/g, "'") ?? null;
  const packageRoot = get("ORCH_ROOT");
  const node = get("ORCH_INSTALL_NODE");
  return packageRoot && node ? { packageRoot, node } : null;
}

/** Write (or repoint) the shim. Refuses to replace a file that is not an Orchestrator launcher. */
export function writeShim(home: string, input: { packageRoot: string; node: string }): { path: string; changed: boolean; previous: string | null } {
  const file = shimPath(home);
  const content = renderShim(input);
  if (existsSync(file)) {
    const current = readFileSync(file, "utf8");
    if (!current.includes(SHIM_MARKER)) throw new Error(`${file} exists and is not an Orchestrator launcher; move it away first`);
    if (current === content) return { path: file, changed: false, previous: input.packageRoot };
  }
  const previous = readShimTarget(file)?.packageRoot ?? null;
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  chmodSync(file, 0o755);
  return { path: file, changed: true, previous };
}

/**
 * Is this package root likely to disappear? Linked git worktrees (T3 and other tools create and
 * delete them), temp directories, and T3's worktree area. A shim pointing there breaks later.
 */
export function ephemeralReasons(packageRoot: string, env: NodeJS.ProcessEnv = process.env): string[] {
  const reasons: string[] = [];
  const real = safeReal(packageRoot);
  const gitEntry = join(real, ".git");
  try {
    if (lstatSync(gitEntry).isFile()) reasons.push("it is a linked git worktree (worktrees are routinely deleted)");
  } catch {
    /* no .git: a packaged install */
  }
  const tmp = safeReal(tmpdir());
  if (real === tmp || real.startsWith(tmp + sep) || real.startsWith("/tmp/") || real.startsWith("/private/tmp/")) reasons.push("it is in a temporary directory");
  const t3 = env.HOME ? safeReal(resolve(env.HOME, ".t3", "worktrees")) : null;
  if (t3 && real.startsWith(t3 + sep)) reasons.push("it is in T3's worktree area (~/.t3/worktrees)");
  return [...new Set(reasons)];
}

function safeReal(p: string): string {
  try {
    return realpathSync(p);
  } catch {
    return resolve(p);
  }
}
