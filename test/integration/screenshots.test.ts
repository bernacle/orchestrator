import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { deflateSync } from "node:zlib";
import { afterAll, afterEach, describe, expect, it } from "vitest";
import { startRun } from "../../src/app.js";
import type { RunContext } from "../../src/core/workflow.js";
import { createHarness, git, makePng, type Harness } from "../helpers.js";

let h: Harness;
afterEach(() => h?.cleanup());

const start = () => startRun(h.app, { issueKey: "ACM-1", repo: "acme/widget", configFile: h.configFile, dryRun: false, ciWaitMinutes: 0 });

// Stand-ins for what a browser test writes: a valid PNG, and PNGs that hide a token in their pixel
// data, once as literal bytes (a stored deflate block) and once compressed (only the decompressed
// image data shows it).
const fixtures = mkdtempSync(join(tmpdir(), "orch-shot-fixtures-"));
afterAll(() => rmSync(fixtures, { recursive: true, force: true }));
const GOOD = join(fixtures, "good.png");
const LEAKY = join(fixtures, "leaky.png");
writeFileSync(GOOD, makePng());
writeFileSync(LEAKY, makePng({ idat: deflateSync(Buffer.from(`\0ghp_${"A".repeat(36)}`), { level: 0 }) }));
const PIXEL_LEAK = join(fixtures, "pixel-leak.png");
writeFileSync(PIXEL_LEAK, makePng({ idat: deflateSync(Buffer.from(`\0ghp_${"B".repeat(36)}`), { level: 9 }) }));
const WRITE_PNG = `mkdir -p shots && cp '${GOOD}' shots/home.png`;

describe("orchestrator-generated screenshots", () => {
  it("generates screenshots from the implementation, commits them, shows them to the reviewer and embeds them in the PR", async () => {
    h = createHarness({ config: { screenshots: { run: WRITE_PNG, outputs: ["shots/*.png"] } } });
    const run = await start();
    expect(run.state).toBe("READY_TO_MERGE");
    const c = run.context as RunContext;

    // Committed on the pushed branch, in a commit of its own on top of the implementer's.
    const pushed = git(h.origin, "rev-parse", `refs/heads/${c.branch}`);
    expect(pushed).toBe(c.reviewedSha);
    expect(git(h.origin, "cat-file", "-t", `${pushed}:shots/home.png`)).toBe("blob");
    expect(git(h.origin, "log", "-1", "--format=%s", pushed)).toBe("ACM-1: screenshots");
    const shots = c.rounds.at(-1)!.screenshots!;
    expect(shots.files.map((f) => f.path)).toEqual(["shots/home.png"]);
    expect(shots.commitSha).toBe(pushed);

    // The implementer was told it does not make the images; the reviewer got them attached.
    expect(h.implementer.calls[0]!.prompt).toContain("Screenshots (generated by the orchestrator, not by you)");
    // The reviewer sees copies of the committed bytes, kept where repository code cannot write.
    expect(h.reviewer.calls[0]!.images).toEqual([join(h.home, "runs", run.id, "screenshots-0", "shots/home.png")]);
    expect(readFileSync(h.reviewer.calls[0]!.images![0]!)).toEqual(readFileSync(GOOD));
    expect(Number(git(h.origin, "cat-file", "-s", `${pushed}:shots/home.png`))).toBe(readFileSync(GOOD).length);
    expect(h.reviewer.calls[0]!.prompt).toContain("## Orchestrator-generated screenshots");

    // The PR renders the images from the reviewed commit.
    const body = (h.host.prs[0] as unknown as { body: string }).body;
    expect(body).toContain("## Screenshots (generated by the orchestrator from the reviewed commit)");
    expect(body).toContain(`![shots/home.png](https://github.com/acme/widget/blob/${pushed}/shots/home.png?raw=true)`);

    // Sandboxed like a check, with no outbound network.
    if (process.platform === "darwin") expect(readFileSync(join(h.home, "runs", run.id, "screenshots-0.log"), "utf8")).toContain("[sandbox: seatbelt, network=none]");
  });

  it("skips screenshots when the change touches none of when_changed", async () => {
    h = createHarness({ config: { screenshots: { run: WRITE_PNG, outputs: ["shots/*.png"], when_changed: ["ui/**"] } } });
    const run = await start();
    expect(run.state).toBe("READY_TO_MERGE");
    expect(() => git(h.origin, "cat-file", "-e", `${run.context.reviewedSha}:shots/home.png`)).toThrow();
    expect(h.reviewer.calls[0]!.images).toBeUndefined();
    expect(h.app.store.events(run.id).map((e) => e.type)).toContain("screenshots.skipped");
  });

  it("sends 'no screenshots written' back to the implementer, then accepts the images its fix produces", async () => {
    h = createHarness({
      config: { screenshots: { run: `if [ -f make-shot ]; then ${WRITE_PNG}; fi`, outputs: ["shots/*.png"] } },
      implement: (task, call) => {
        writeFileSync(join(task.cwd, "feature.txt"), "hello\n");
        if (call === 2) writeFileSync(join(task.cwd, "make-shot"), "1\n"); // e.g. adds the missing page.screenshot
        return {};
      },
    });
    const run = await start();
    expect(run.state).toBe("READY_TO_MERGE");
    expect(h.implementer.calls).toHaveLength(2);
    expect(h.implementer.calls[1]!.prompt).toMatch(/screenshots could not be produced/);
    expect(h.implementer.calls[1]!.prompt).toMatch(/wrote no image matching shots\/\*\.png/);
    expect(git(h.origin, "cat-file", "-t", `${run.context.reviewedSha}:shots/home.png`)).toBe("blob");
  });

  it("never commits files that are not images, and fails when the rounds run out", async () => {
    h = createHarness({
      config: { screenshots: { run: "mkdir -p shots && echo 'not an image' > shots/home.png", outputs: ["shots/*.png"] } },
      implement: (task, call) => {
        writeFileSync(join(task.cwd, "feature.txt"), `hello ${call}\n`);
        return {};
      },
    });
    const run = await start();
    expect(run.state).toBe("FAILED");
    expect(run.reason).toMatch(/screenshots still missing after 2 correction round\(s\): unusable screenshot files: shots\/home\.png is not a PNG/);
    expect(h.reviewer.calls).toHaveLength(0);
    expect(h.host.prs).toHaveLength(0);
    expect(git(join(run.context.worktreePath!), "ls-files", "shots")).toBe("");
  });

  it("fails closed when a screenshot's bytes contain a token, before anything is committed or pushed", async () => {
    h = createHarness({ config: { screenshots: { run: `mkdir -p shots && cp '${LEAKY}' shots/home.png`, outputs: ["shots/*.png"] } } });
    const run = await start();
    expect(run.state).toBe("FAILED");
    expect(run.reason).toMatch(/possible secret in screenshot shots\/home\.png \(GitHub token\)/);
    expect(run.reason).not.toContain("ghp_");
    expect(h.reviewer.calls).toHaveLength(0);
    expect(h.host.prs).toHaveLength(0);
    expect(git(run.context.worktreePath!, "ls-files", "shots")).toBe("");
  });

  it("scans the decompressed image data too, so compressing a token does not hide it", async () => {
    h = createHarness({ config: { screenshots: { run: `mkdir -p shots && cp '${PIXEL_LEAK}' shots/home.png`, outputs: ["shots/*.png"] } } });
    const run = await start();
    expect(run.state).toBe("FAILED");
    expect(run.reason).toMatch(/possible secret in screenshot shots\/home\.png \(image data\)/);
    expect(h.host.prs).toHaveLength(0);
  });

  it("a base that renders screenshots itself does not make the baseline dirty", async () => {
    // Once earlier screenshot PRs are merged, the base's own smoke tests rewrite those files.
    h = createHarness({ config: { baseline_checks: true, checks: [{ name: "ok", run: "true" }], screenshots: { run: WRITE_PNG, outputs: ["shots/*.png"] } } });
    const run = await start();
    expect(run.state).toBe("READY_TO_MERGE");
    expect(h.implementer.calls).toHaveLength(1);
    expect(git(h.origin, "cat-file", "-t", `${run.context.reviewedSha}:shots/home.png`)).toBe("blob");
  });

  it("refuses an image the implementer put under outputs by hand, until it is removed", async () => {
    h = createHarness({
      config: { screenshots: { run: WRITE_PNG, outputs: ["shots/*.png"], when_changed: ["ui/**"] } },
      implement: (task, call) => {
        writeFileSync(join(task.cwd, "feature.txt"), `hello ${call}\n`);
        if (call === 1) {
          mkdirSync(join(task.cwd, "shots"), { recursive: true });
          writeFileSync(join(task.cwd, "shots", "made-by-hand.png"), makePng()); // valid, but not produced by the command
        } else rmSync(join(task.cwd, "shots", "made-by-hand.png"), { force: true });
        return {};
      },
    });
    const run = await start();
    expect(run.state).toBe("READY_TO_MERGE");
    expect(h.implementer.calls).toHaveLength(2);
    expect(h.implementer.calls[1]!.prompt).toMatch(/did not produce \(hand-made or stale.*\): shots\/made-by-hand\.png/);
    // Touching outputs made screenshots required even though when_changed did not match.
    expect(() => git(h.origin, "cat-file", "-e", `${run.context.reviewedSha}:shots/made-by-hand.png`)).toThrow();
    // With the image gone, the change touches neither ui/** nor outputs: no screenshots are needed.
    expect(h.app.store.events(run.id).map((e) => e.type)).toContain("screenshots.skipped");
  });

  it("blocks before the implementer starts when screenshots cannot be generated on the untouched base", async () => {
    h = createHarness({ config: { baseline_checks: true, checks: [{ name: "ok", run: "true" }], screenshots: { run: "echo 'chromium: Executable does not exist' >&2; exit 3", outputs: ["shots/*.png"] } } });
    const run = await start();
    expect(run.state).toBe("BLOCKED");
    expect(run.reason).toMatch(/red before any change: screenshots/);
    expect(run.reason).toMatch(/Screenshots cannot be generated in this environment/);
    expect(h.implementer.calls).toHaveLength(0);
  });
});
